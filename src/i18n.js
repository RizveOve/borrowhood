// Dugnad texts live in their own file.
Object.assign(en, require('./i18n-dugnad').en);
Object.assign(nb, require('./i18n-dugnad').nb);

const DICTS = { en, nb };
const LANGS = Object.keys(DICTS);

function translator(lang) {
  const dict = DICTS[lang] || en;
  return (key, vars = {}) => {
    const s = dict[key] ?? en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  };
}

// Preferred language: logged-in user's setting, then cookie session, then the browser's Accept-Language.
function pickLang(req) {
  const fromUser = req.user && req.user.lang;
  const fromSession = req.session && req.session.lang;
  if (LANGS.includes(fromUser)) return fromUser;
  if (LANGS.includes(fromSession)) return fromSession;
  return /^(nb|no|nn)\b/i.test(req.get('Accept-Language') || '') ? 'nb' : 'en';
}

module.exports = { translator, pickLang, LANGS, DICTS };
